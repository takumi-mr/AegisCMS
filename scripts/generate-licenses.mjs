import { execSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

console.log('Extracting Rust crate metadata...');
const cargoOutput = execSync('cargo metadata --format-version 1', {
  cwd: rootDir,
  maxBuffer: 50 * 1024 * 1024,
  encoding: 'utf8',
});
const cargoMeta = JSON.parse(cargoOutput);

const rustPackages = [];
const seenRust = new Set();
for (const pkg of cargoMeta.packages) {
  if (!pkg.source) continue;
  const key = `${pkg.name}@${pkg.version}`;
  if (seenRust.has(key)) continue;
  seenRust.add(key);

  rustPackages.push({
    name: pkg.name,
    version: pkg.version,
    license: pkg.license || 'Unknown',
    repository: pkg.repository || null,
    description: pkg.description || null,
  });
}
rustPackages.sort((a, b) => a.name.localeCompare(b.name));

console.log('Extracting npm packages from admin, theme-builder, and plugin-builder...');
const npmDirs = ['admin', 'theme-builder', 'plugin-builder'];
const npmPackages = [];
const seenNpm = new Set();

for (const dir of npmDirs) {
  const lockPath = path.join(rootDir, dir, 'package-lock.json');
  if (!fs.existsSync(lockPath)) continue;

  const lock = JSON.parse(fs.readFileSync(lockPath, 'utf8'));
  const packages = lock.packages || {};

  for (const [pkgPath, info] of Object.entries(packages)) {
    if (!pkgPath || info.dev) continue;
    const name = pkgPath.replace(/^node_modules\//, '');
    const version = info.version;
    const key = `${name}@${version}`;
    if (seenNpm.has(key)) continue;
    seenNpm.add(key);

    let repo = null;
    if (typeof info.repository === 'string') {
      repo = info.repository;
    } else if (info.repository?.url) {
      repo = info.repository.url;
    }

    npmPackages.push({
      name,
      version,
      license: info.license || 'Unknown',
      repository: repo,
      usedIn: dir,
    });
  }
}
npmPackages.sort((a, b) => a.name.localeCompare(b.name));

const licenseData = {
  rust: rustPackages,
  npm: npmPackages,
};

const adminDataDir = path.join(rootDir, 'admin', 'src', 'data');
if (!fs.existsSync(adminDataDir)) {
  fs.mkdirSync(adminDataDir, { recursive: true });
}
const adminJsonPath = path.join(adminDataDir, 'licenses.json');
fs.writeFileSync(adminJsonPath, JSON.stringify(licenseData, null, 2), 'utf8');
console.log(`Wrote ${adminJsonPath} (${rustPackages.length} Rust crates, ${npmPackages.length} npm packages)`);

let markdown = `# Third-Party Licenses / サードパーティライセンス一覧\n\n`;
markdown += `AegisCMS uses the following open-source third-party libraries and crates.\n\n`;
markdown += `This file was automatically generated by \`node scripts/generate-licenses.mjs\`.\n\n`;

markdown += `## Backend Dependencies (Rust Crates)\n\n`;
markdown += `| Package | Version | License | Repository |\n`;
markdown += `| :--- | :--- | :--- | :--- |\n`;
for (const p of rustPackages) {
  const repo = p.repository ? `[Link](${p.repository})` : '-';
  markdown += `| \`${p.name}\` | \`${p.version}\` | ${p.license} | ${repo} |\n`;
}

markdown += `\n## Frontend Dependencies (npm Packages)\n\n`;
markdown += `| Package | Version | License | Used In | Repository |\n`;
markdown += `| :--- | :--- | :--- | :--- | :--- |\n`;
for (const p of npmPackages) {
  const repoUrl = p.repository ? p.repository.replace(/^git\+/, '').replace(/\.git$/, '') : null;
  const repo = repoUrl ? `[Link](${repoUrl})` : '-';
  markdown += `| \`${p.name}\` | \`${p.version}\` | ${p.license} | \`${p.usedIn}\` | ${repo} |\n`;
}

const mdPath = path.join(rootDir, 'THIRD_PARTY_LICENSES.md');
fs.writeFileSync(mdPath, markdown, 'utf8');
console.log(`Wrote ${mdPath}`);

