use std::collections::HashSet;

use super::to_pascal_case;
use crate::definition::{FieldDefinition, FieldType, SchemaDefinition};

pub struct TypeScriptGenerator;

impl TypeScriptGenerator {
    /// Generate complete TypeScript type definitions (.d.ts / .ts) for the given schemas.
    pub fn generate(schemas: &[SchemaDefinition]) -> String {
        let mut out = String::new();

        out.push_str("/**\n");
        out.push_str(" * AegisCMS Auto-Generated TypeScript Type Definitions\n");
        out.push_str(" * Generated by: aegis-schema codegen\n");
        out.push_str(" * Do not edit this file directly.\n");
        out.push_str(" */\n\n");

        // 1. Core Common Types
        out.push_str(
            "// ============================================================================\n",
        );
        out.push_str("// Core Common Types\n");
        out.push_str(
            "// ============================================================================\n\n",
        );

        out.push_str("export interface BlockNode {\n");
        out.push_str("  name: string;\n");
        out.push_str("  attributes: Record<string, any>;\n");
        out.push_str("  children?: BlockNode[];\n");
        out.push_str("  text?: string;\n");
        out.push_str("}\n\n");

        out.push_str(
            "export type ContentStatus = 'draft' | 'scheduled' | 'published' | 'archived';\n\n",
        );

        out.push_str("export interface BaseContentItem {\n");
        out.push_str("  id: string;\n");
        out.push_str("  content_type: string;\n");
        out.push_str("  title: string;\n");
        out.push_str("  slug: string;\n");
        out.push_str("  status: ContentStatus;\n");
        out.push_str("  blocks: BlockNode[];\n");
        out.push_str("  rendered_html: string;\n");
        out.push_str("  author_id?: string | null;\n");
        out.push_str("  published_at?: string | null;\n");
        out.push_str("  created_at: string;\n");
        out.push_str("  updated_at: string;\n");
        out.push_str("}\n\n");

        // 2. Schema-specific Content Types
        out.push_str(
            "// ============================================================================\n",
        );
        out.push_str("// Schema-Specific Content Types & Payloads\n");
        out.push_str(
            "// ============================================================================\n\n",
        );

        for schema in schemas {
            let pascal = to_pascal_case(&schema.content_type);

            // JSDoc
            out.push_str("/**\n");
            out.push_str(&format!(" * {}\n", schema.label));
            if let Some(desc) = &schema.description {
                out.push_str(&format!(" * {}\n", desc));
            }
            out.push_str(&format!(" * Schema: `{}`\n", schema.content_type));
            out.push_str(" */\n");

            // Content Interface
            out.push_str(&format!("export interface {}Content {{\n", pascal));
            out.push_str("  id: string;\n");
            out.push_str(&format!("  content_type: '{}';\n", schema.content_type));
            out.push_str("  status: ContentStatus;\n");
            out.push_str("  blocks: BlockNode[];\n");
            out.push_str("  rendered_html: string;\n");
            out.push_str("  author_id?: string | null;\n");
            out.push_str("  created_at: string;\n");
            out.push_str("  updated_at: string;\n");

            // Standard fields handled above to avoid duplicate property declarations
            let standard_fields: HashSet<&str> = [
                "id",
                "content_type",
                "status",
                "blocks",
                "rendered_html",
                "author_id",
                "created_at",
                "updated_at",
            ]
            .into_iter()
            .collect();

            // Emit schema fields
            for field in &schema.fields {
                if standard_fields.contains(field.name.as_str()) {
                    continue;
                }
                out.push_str(&Self::format_ts_property(field, false));
            }
            out.push_str("}\n\n");

            // Create Payload Interface
            out.push_str(&format!("export interface Create{}Payload {{\n", pascal));
            out.push_str("  title: string;\n");
            out.push_str("  slug: string;\n");
            out.push_str("  status?: ContentStatus;\n");
            out.push_str("  blocks?: BlockNode[];\n");
            out.push_str("  author_id?: string | null;\n");

            let create_standard_fields: HashSet<&str> =
                ["title", "slug", "status", "blocks", "author_id"]
                    .into_iter()
                    .collect();

            for field in &schema.fields {
                if create_standard_fields.contains(field.name.as_str()) {
                    continue;
                }
                out.push_str(&Self::format_ts_property(field, true));
            }
            out.push_str("}\n\n");

            // Update Payload Interface (all schema fields optional)
            out.push_str(&format!("export interface Update{}Payload {{\n", pascal));
            out.push_str("  title?: string;\n");
            out.push_str("  slug?: string;\n");
            out.push_str("  status?: ContentStatus;\n");
            out.push_str("  blocks?: BlockNode[];\n");
            out.push_str("  author_id?: string | null;\n");

            for field in &schema.fields {
                if create_standard_fields.contains(field.name.as_str()) {
                    continue;
                }
                out.push_str(&Self::format_ts_optional_property(field));
            }
            out.push_str("}\n\n");
        }

        // 3. Union & Map Types
        out.push_str(
            "// ============================================================================\n",
        );
        out.push_str("// Union & Type Registry Mappings\n");
        out.push_str(
            "// ============================================================================\n\n",
        );

        if schemas.is_empty() {
            out.push_str("export type ContentType = string;\n\n");
            out.push_str("export type AnyContent = BaseContentItem;\n\n");
            out.push_str("export interface ContentTypeMap {}\n\n");
            out.push_str("export interface CreatePayloadMap {}\n");
        } else {
            // ContentType union
            let types_union = schemas
                .iter()
                .map(|s| format!("'{}'", s.content_type))
                .collect::<Vec<_>>()
                .join(" | ");
            out.push_str(&format!("export type ContentType = {};\n\n", types_union));

            // AnyContent union
            let any_content = schemas
                .iter()
                .map(|s| format!("{}Content", to_pascal_case(&s.content_type)))
                .collect::<Vec<_>>()
                .join(" | ");
            out.push_str(&format!("export type AnyContent = {};\n\n", any_content));

            // ContentTypeMap
            out.push_str("export interface ContentTypeMap {\n");
            for schema in schemas {
                let pascal = to_pascal_case(&schema.content_type);
                out.push_str(&format!(
                    "  '{}': {}Content;\n",
                    schema.content_type, pascal
                ));
            }
            out.push_str("}\n\n");

            // CreatePayloadMap
            out.push_str("export interface CreatePayloadMap {\n");
            for schema in schemas {
                let pascal = to_pascal_case(&schema.content_type);
                out.push_str(&format!(
                    "  '{}': Create{}Payload;\n",
                    schema.content_type, pascal
                ));
            }
            out.push_str("}\n");
        }

        out
    }

    fn field_type_to_ts(field_type: &FieldType) -> &'static str {
        match field_type {
            FieldType::String | FieldType::Text => "string",
            FieldType::Integer => "number",
            FieldType::Boolean => "boolean",
            FieldType::Timestamp => "string",
            FieldType::Relation => "string",
            FieldType::Jsonb => "Record<string, any>",
        }
    }

    fn format_ts_property(field: &FieldDefinition, is_create_payload: bool) -> String {
        let ts_type = Self::field_type_to_ts(&field.field_type);
        let optional = !field.required || field.nullable || is_create_payload;
        let opt_mark = if optional { "?" } else { "" };
        let null_mark = if field.nullable { " | null" } else { "" };

        format!("  {}{}: {}{};\n", field.name, opt_mark, ts_type, null_mark)
    }

    fn format_ts_optional_property(field: &FieldDefinition) -> String {
        let ts_type = Self::field_type_to_ts(&field.field_type);
        let null_mark = if field.nullable { " | null" } else { "" };
        format!("  {}?: {}{};\n", field.name, ts_type, null_mark)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::definition::{FieldDefinition, FieldType, SchemaDefinition};

    #[test]
    fn test_generate_typescript() {
        let schema = SchemaDefinition {
            content_type: "article".to_string(),
            label: "技術記事".to_string(),
            description: Some("技術ブログ記事".to_string()),
            fields: vec![
                FieldDefinition {
                    name: "title".to_string(),
                    field_type: FieldType::String,
                    required: true,
                    nullable: false,
                    unique: false,
                    index: true,
                    max_length: Some(255),
                    target: None,
                    indexed_paths: vec![],
                },
                FieldDefinition {
                    name: "excerpt".to_string(),
                    field_type: FieldType::String,
                    required: false,
                    nullable: true,
                    unique: false,
                    index: false,
                    max_length: Some(500),
                    target: None,
                    indexed_paths: vec![],
                },
                FieldDefinition {
                    name: "custom_meta".to_string(),
                    field_type: FieldType::Jsonb,
                    required: false,
                    nullable: false,
                    unique: false,
                    index: false,
                    max_length: None,
                    target: None,
                    indexed_paths: vec![],
                },
            ],
        };

        let ts = TypeScriptGenerator::generate(&[schema]);
        assert!(ts.contains("export interface ArticleContent {"));
        assert!(ts.contains("export interface CreateArticlePayload {"));
        assert!(ts.contains("export type ContentType = 'article';"));
        assert!(ts.contains("excerpt?: string | null;"));
        assert!(ts.contains("custom_meta?: Record<string, any>;"));
    }
}
